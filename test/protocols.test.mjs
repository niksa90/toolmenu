// The protocol support table, docs/PROTOCOLS.md, is this test's output: every cell is
// something it just ran. A protocol version toolmenu ships a schema for gets a
// handshake, the schema check on a good and a bad tools/list, and a session whose call
// adds a tool mid-list. When the table and the run disagree, the test fails;
// UPDATE_DOCS=1 writes the table again from the run.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MENU_RULES, runRules } from '../dist/rules/index.js';
import { parseScenario, session } from '../dist/session.js';
import { FIXTURES, ROOT, menuOf, TIMEOUT_MS } from './helpers.mjs';

const DOC = join(ROOT, 'docs/PROTOCOLS.md');
const MODERN = '2026-07-28';
const versions = readdirSync(join(ROOT, 'schemas'))
  .filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();

/** The server for a version: the SDK v2 fixture for 2026-07-28, the hand-rolled one before it. */
function target(version) {
  return version === MODERN
    ? { kind: 'stdio', command: process.execPath, args: [join(FIXTURES, 'session-server.mjs')] }
    : { kind: 'stdio', command: process.execPath, args: [join(FIXTURES, 'protocol-server.mjs')], env: { PROTOCOL: version } };
}
const unlockStep = (version) => (version === MODERN ? { call: 'unlock_toolset', args: { toolset: 'audits' } } : { call: 'unlock' });

/** spec/schema on a tools/list page, as snapshot runs it. */
function schemaFindings(version, page) {
  return runRules(MENU_RULES, { menu: menuOf([]), pages: [page], capabilities: {}, usedAuth: false, protocolVersion: version }).filter((f) => f.rule === 'spec/schema');
}
const GOOD_TOOL = { name: 'ok', inputSchema: { type: 'object' } };
// 2026-07-28 results also carry ttlMs, cacheScope and resultType.
const goodPage = (version) => (version >= MODERN ? { tools: [GOOD_TOOL], ttlMs: 60000, cacheScope: 'private', resultType: 'complete' } : { tools: [GOOD_TOOL] });
// An inputSchema without "type": "object", which every version requires.
const badPage = (version) => ({ ...goodPage(version), tools: [{ name: 'bad', inputSchema: {} }] });

async function measure(version) {
  const scenario = parseScenario({ steps: ['list', unlockStep(version)] });
  const r = await session(target(version), scenario, { timeoutMs: TIMEOUT_MS });
  const step = r.steps[1];
  const ruleOf = (f) => `\`${f.rule}\` (${f.severity})`;
  const change = r.findings.filter((f) => f.step === 2 && /^session\/(?:mid-insert|append|reorder|remove|edit)$/.test(f.rule));
  const local = r.findings.filter((f) => f.step === 2 && /^session\/(?:side-effect|connection-local)$/.test(f.rule));
  const good = schemaFindings(version, goodPage(version));
  const bad = schemaFindings(version, badPage(version));
  const applies = MENU_RULES.filter((rule) => !rule.since || version >= rule.since).length;
  return {
    version,
    handshake: r.server.protocolVersion === version ? (r.server.era === 'modern' ? '`server/discover`' : '`initialize`') : `✗ got ${r.server.protocolVersion}`,
    schema: good.length === 0 && bad.length === 1 && bad[0].severity === 'error' ? '✓' : `✗ good: ${good.length}, bad: ${bad.map((f) => f.severity).join('/') || 'none'}`,
    pinned: change.length && step.changed ? `✓ ${change.map(ruleOf).join(', ')}${step.listChanged > 0 ? ', `list_changed` received' : ''}` : '✗',
    local: step.scope === 'per-process' ? (local.length ? local.map(ruleOf).join(', ') : 'allowed: no finding') : `✗ scope ${step.scope ?? 'unchecked'}`,
    rules: `${applies} of ${MENU_RULES.length}`,
  };
}

function render(rows) {
  return `# Protocol support

Generated by \`test/protocols.test.mjs\`, which runs every row against a fixture server
on each \`npm test\`: a cell says what that run saw, not what toolmenu is meant to do.
\`UPDATE_DOCS=1 node --test test/protocols.test.mjs\` writes it again.

One row per protocol version toolmenu ships the official schema for (\`schemas/\`).
2026-07-28 is served by the official TypeScript SDK v2; the 2025-era versions by a
hand-rolled server (\`test/fixtures/protocol-server.mjs\`), so the version it answers is
exactly the one in the row.

| Protocol | Handshake | \`tools/list\` against its schema | Mid-session change, pinned to its step | A change only this session sees | \`snapshot\` rules that apply |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.version} | ${r.handshake} | ${r.schema} | ${r.pinned} | ${r.local} | ${r.rules} |`).join('\n')}

- **Handshake**: the request toolmenu connected with, and the server answering that version.
- **\`tools/list\` against its schema**: \`spec/schema\` passes a valid result and reports an
  error for one whose \`inputSchema\` has no \`"type": "object"\`.
- **Mid-session change**: a call that adds a tool in the middle of the list, found at
  that call's step.
- **A change only this session sees**: a fresh server process doesn't show it. The 2025
  versions allow that; 2026-07-28 says the tool set MUST NOT change as a side effect of
  requests (over HTTP, \`session/connection-local\` is an error).
- **Rules that apply**: the rest are 2026-07-28 rules, skipped on older servers.
`;
}

test('the protocol support table (docs/PROTOCOLS.md) is what a run of every version sees', async () => {
  assert.ok(versions.includes(MODERN) && versions.length >= 5, `schemas/: ${versions.join(', ')}`);
  const rows = [];
  for (const v of versions) rows.push(await measure(v));
  for (const r of rows) assert.ok(!Object.values(r).some((cell) => String(cell).startsWith('✗')), `${r.version}: ${JSON.stringify(r)}`);
  const doc = render(rows);
  if (process.env.UPDATE_DOCS) writeFileSync(DOC, doc);
  let committed = '';
  try {
    committed = readFileSync(DOC, 'utf8');
  } catch {}
  assert.equal(committed, doc, 'docs/PROTOCOLS.md is out of date: UPDATE_DOCS=1 node --test test/protocols.test.mjs');
});
